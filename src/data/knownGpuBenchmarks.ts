/**
 * Searches raw text for known GPU chip names and aliases.
 * Prioritizes longer/more specific patterns first to avoid greedy substring conflicts
 * (e.g. "RTX 4070 Super" matches before "RTX 4070").
 */
export function matchKnownGpuChip(rawText: string): KnownGpuBenchmark | null {
  if (!rawText || !rawText.trim()) return null;

  const normalized = rawText
    .toLowerCase()
    .replace(/[,\-_/]/g, ' ')
    .replace(/\s+/g, ' ');

  for (const benchmark of KNOWN_GPU_BENCHMARKS) {
    for (const alias of benchmark.aliases) {
      // Word boundary regex for alias
      const escaped = alias.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const pattern = new RegExp(`(?:^|\\b)${escaped}(?:\\b|$)`, 'i');
      if (pattern.test(normalized)) {
        return benchmark;
      }
    }
  }

  return null;
}
