/**
 * sync-claude-skills.cjs
 *
 * Skills live in .agents/skills/, the cross-tool location Antigravity and
 * Gemini CLI read natively. Claude Code discovers .claude/skills/, so each
 * skill gets a generated pointer stub there with the source frontmatter.
 *
 * Run:   npm run sync:skills   (writes missing/stale stubs, removes orphans)
 * Check: check-docs.cjs calls diffStubs() and fails on any drift.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SOURCE_DIR = path.join(ROOT, '.agents', 'skills');
const STUB_DIR = path.join(ROOT, '.claude', 'skills');

const NOT_STUBBED = new Set(['skill-library']);
const MARKER = 'Generated by scripts/sync-claude-skills.cjs';

const normalise = (text) => text.replace(/\r\n/g, '\n');

function renderStub(name, source) {
  const frontmatter = normalise(source).match(/^---\n[\s\S]*?\n---/);
  if (!frontmatter) return null;
  const home = `.agents/skills/${name}`;
  return [
    frontmatter[0],
    '',
    `<!-- ${MARKER}. Edit ${home}/SKILL.md, then run npm run sync:skills. -->`,
    '',
    `This skill lives in \`${home}/\`, shared with Antigravity and Gemini CLI.`,
    '',
    `Read \`${home}/SKILL.md\` now and follow it. Relative paths in it resolve from \`${home}/\`.`,
    '',
  ].join('\n');
}

function expectedStubs() {
  const stubs = new Map();
  if (!fs.existsSync(SOURCE_DIR)) return stubs;
  for (const entry of fs.readdirSync(SOURCE_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory() || NOT_STUBBED.has(entry.name)) continue;
    const skillFile = path.join(SOURCE_DIR, entry.name, 'SKILL.md');
    if (!fs.existsSync(skillFile)) continue;
    const stub = renderStub(entry.name, fs.readFileSync(skillFile, 'utf-8'));
    if (stub) stubs.set(entry.name, stub);
  }
  return stubs;
}

function orphanedStubs(expected) {
  if (!fs.existsSync(STUB_DIR)) return [];
  return fs
    .readdirSync(STUB_DIR, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !expected.has(e.name))
    .map((e) => e.name)
    .filter((name) => {
      const file = path.join(STUB_DIR, name, 'SKILL.md');
      return fs.existsSync(file) && fs.readFileSync(file, 'utf-8').includes(MARKER);
    });
}

function diffStubs() {
  const expected = expectedStubs();
  const missing = [];
  const stale = [];
  for (const [name, content] of expected) {
    const file = path.join(STUB_DIR, name, 'SKILL.md');
    if (!fs.existsSync(file)) missing.push(name);
    else if (normalise(fs.readFileSync(file, 'utf-8')) !== content) stale.push(name);
  }
  return { expected, missing, stale, orphaned: orphanedStubs(expected) };
}

function sync() {
  const { expected, missing, stale, orphaned } = diffStubs();
  for (const name of [...missing, ...stale]) {
    fs.mkdirSync(path.join(STUB_DIR, name), { recursive: true });
    fs.writeFileSync(
      path.join(STUB_DIR, name, 'SKILL.md'),
      expected.get(name).replace(/\n/g, '\r\n')
    );
  }
  for (const name of orphaned) {
    fs.rmSync(path.join(STUB_DIR, name), { recursive: true, force: true });
  }
  console.log(
    `[sync-claude-skills] ${expected.size} skills: ${missing.length} added, ` +
      `${stale.length} updated, ${orphaned.length} removed.`
  );
}

module.exports = { diffStubs };

if (require.main === module) sync();
